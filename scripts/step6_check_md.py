"""
Step 6: check the MACE molecular dynamics of step 5 against DFT and against the MD17 trajectory.

1. Configurations that MACE generated itself are not in the dataset. Twenty of them, taken at random from the
   NVT run after equilibration, are recomputed with ORCA at the rMD17 level (PBE/def2-SVP); their errors show
   whether MACE stays as accurate during its own dynamics as on the test set.
2. The distributions of the hydroxyl torsion H-O-C-C and of the methyl torsion H-C-C-O in the MACE run are
   compared with those of the 500 K ab initio trajectory of MD17 (data/rmd17_ethanol_torsions.npz). The MD17
   trajectory was run with PBE+vdW-TS, not exactly the PBE/def2-SVP surface of the labels, so close agreement,
   not identity, is expected.
3. Energy conservation of the NVE run: drift of the total energy (linear fit) and its standard deviation.

Writes
    results/md_orca_check.csv            energy of every checked frame, MACE and ORCA (eV)
    results/md_orca_check_forces.csv     force components, MACE and ORCA (eV/Å)
    results/md_torsions.csv              torsion angles of every saved frame of the NVT run (degrees)
    results/md_summary.json              all numbers of the check

Run:  ORCA_EXE=/full/path/to/orca python scripts/step6_check_md.py
"""
import argparse
import csv
import json
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
from ase.io import read
from mace.calculators import MACECalculator

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mlip_style import DATA_DIR, MODEL_DIR, ORCA_DIR, RESULTS_DIR, WORK_DIR  # noqa: E402
from orca_tools import run_single_point  # noqa: E402
from step1_prepare_rmd17 import dihedral_angles, torsion_atoms  # noqa: E402

EQUILIBRATION_PS = 10.0    # first part of the NVT run, left out of all averages
SEED = 11                  # random choice of the frames recomputed with ORCA


def read_table(path):
    """Columns of a CSV table written by step 5, as a dictionary of arrays."""
    with open(path) as table:
        reader = csv.DictReader(table)
        rows = list(reader)
    columns = {}
    for name in rows[0]:
        columns[name] = np.array([float(row[name]) for row in rows])
    return columns


def trans_fraction(hydroxyl_deg):
    """Fraction of frames with the hydroxyl hydrogen trans to the methyl carbon (|H-O-C-C| > 120 degrees)."""
    return float(np.mean(np.abs(hydroxyl_deg) > 120.0))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    parser.add_argument('--n-frames', type=int, default=20)
    parser.add_argument('--workers', type=int, default=6, help='ORCA calculations at the same time')
    parser.add_argument('--model', default=str(MODEL_DIR / 'ethanol_N1000_stagetwo.model'))
    args = parser.parse_args()

    frames = read(WORK_DIR / 'md' / 'nvt_500K.traj', ':')
    nvt = read_table(RESULTS_DIR / 'md_nvt_500K.csv')
    nve = read_table(RESULTS_DIR / 'md_nve.csv')
    production = nvt['time_ps'] > EQUILIBRATION_PS
    production_frames = [frame for frame, keep in zip(frames, production) if keep]

    # ------------------------------------------------------------------
    # 1. ORCA on frames generated by MACE
    # ------------------------------------------------------------------
    rng = np.random.default_rng(SEED)
    chosen = sorted(rng.choice(len(production_frames), args.n_frames, replace=False))
    futures = []
    with ProcessPoolExecutor(args.workers) as pool:
        for i in chosen:
            frame = production_frames[i]
            futures.append(pool.submit(run_single_point, frame.get_chemical_symbols(), frame.positions,
                                       ORCA_DIR / 'mace_md_check' / f'frame_{i:05d}'))
        orca_results = []
        for future in futures:
            orca_results.append(future.result())

    calculator = MACECalculator(model_paths=args.model, device='cpu', default_dtype='float32')
    mace_energies = []
    mace_forces = []
    for i in chosen:
        frame = production_frames[i].copy()
        frame.calc = calculator
        mace_energies.append(frame.get_potential_energy())
        # the frames carry the FixCom constraint of the MD; the raw forces of the model are compared, not the
        # forces projected by the constraint
        mace_forces.append(frame.get_forces(apply_constraint=False))
    mace_energies = np.array(mace_energies)
    mace_forces = np.concatenate(mace_forces).ravel()
    orca_energies = np.array([result[0] for result in orca_results])
    orca_forces = np.concatenate([result[1] for result in orca_results]).ravel()

    # ------------------------------------------------------------------
    # 2. Torsions of the MACE run and of the MD17 trajectory
    # ------------------------------------------------------------------
    numbers = frames[0].numbers
    positions = np.array([frame.positions for frame in production_frames])
    oxygen, carbon_1, carbon_2, hydroxyl_hydrogen, methyl_hydrogens = torsion_atoms(numbers, positions[0])
    hydroxyl = dihedral_angles(positions, hydroxyl_hydrogen, oxygen, carbon_1, carbon_2)
    methyl = dihedral_angles(positions, methyl_hydrogens[0], carbon_2, carbon_1, oxygen) % 120.0
    reference = np.load(DATA_DIR / 'rmd17_ethanol_torsions.npz')

    # ------------------------------------------------------------------
    # 3. Energy conservation of the NVE run
    # ------------------------------------------------------------------
    nve_time = nve['time_ps'] - nve['time_ps'][0]
    drift_slope = np.polyfit(nve_time, nve['total_energy_eV'], 1)[0]

    summary = {
        'md_frames_checked_with_orca': len(chosen),
        'md_energy_offset_meV': float((mace_energies - orca_energies).mean() * 1000),
        'md_relative_energy_mae_meV': float(np.abs((mace_energies - mace_energies.mean())
                                                   - (orca_energies - orca_energies.mean())).mean() * 1000),
        'md_force_mae_meV_per_A': float(np.abs(mace_forces - orca_forces).mean() * 1000),
        'nvt_mean_temperature_K': float(nvt['temperature_K'][production].mean()),
        'nvt_production_ps': float(nvt['time_ps'][-1] - EQUILIBRATION_PS),
        'trans_fraction_mace': trans_fraction(hydroxyl),
        'trans_fraction_md17': trans_fraction(reference['hydroxyl_deg']),
        'nve_total_energy_std_meV': float(nve['total_energy_eV'].std() * 1000),
        'nve_kinetic_energy_std_meV': float(nve['kinetic_energy_eV'].std() * 1000),
        'nve_drift_meV_per_ps': float(drift_slope * 1000),
    }

    with open(RESULTS_DIR / 'md_orca_check.csv', 'w', newline='') as table:
        writer = csv.writer(table)
        writer.writerow(['time_ps', 'mace_energy_eV', 'orca_energy_eV'])
        production_times = nvt['time_ps'][production]
        for k, i in enumerate(chosen):
            writer.writerow([f'{production_times[i]:.4f}', f'{mace_energies[k]:.8f}', f'{orca_energies[k]:.8f}'])
    with open(RESULTS_DIR / 'md_orca_check_forces.csv', 'w', newline='') as table:
        writer = csv.writer(table)
        writer.writerow(['mace_force_eV_per_A', 'orca_force_eV_per_A'])
        for mace_value, orca_value in zip(mace_forces, orca_forces):
            writer.writerow([f'{mace_value:.8f}', f'{orca_value:.8f}'])
    with open(RESULTS_DIR / 'md_torsions.csv', 'w', newline='') as table:
        writer = csv.writer(table)
        writer.writerow(['hydroxyl_deg', 'methyl_deg'])
        for hydroxyl_value, methyl_value in zip(hydroxyl, methyl):
            writer.writerow([f'{hydroxyl_value:.3f}', f'{methyl_value:.3f}'])
    (RESULTS_DIR / 'md_summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
